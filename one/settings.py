# Date-based submission visibility for partner accounts. A user matches a rule
# when they belong to its group_name, or when their username contains one of
# its markers or their email contains one of its domains. Matched users see
# only submissions submitted on/after the rule's start_date — across list,
# detail, export, dashboard, insights, GraphQL, and chart endpoints — and in
# user management they only see/manage users from the same partner group.
# The first matching rule wins.
#
# Rules are deployment configuration and none ship with the code. Set
# PARTNER_VISIBILITY_RULES_JSON to a JSON list, for example:
#   [{"name": "partner-a", "group_name": "Partner A",
#     "username_markers": ["partner-a"], "email_domains": ["@partner-a.example"],
#     "start_date": "2026-01-01", "admin_survey_id": 1}]
PARTNER_VISIBILITY_RULES = [
    {**rule, "start_date": date.fromisoformat(rule["start_date"])}
    if rule.get("start_date")
    else rule
    for rule in json.loads(os.getenv("PARTNER_VISIBILITY_RULES_JSON", "[]"))
]

